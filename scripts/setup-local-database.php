<?php

declare(strict_types=1);

/**
 * Creates the local axa_kenneth_db database, two least-privilege accounts,
 * and a .env file with fresh random credentials. It refuses to overwrite an
 * existing .env and never drops or renames an existing database.
 *
 * Usage:
 *   php scripts/setup-local-database.php
 *
 * Optional environment variables for unattended local setup:
 *   MYSQL_ADMIN_USER (default: root)
 *   MYSQL_ADMIN_PASSWORD (default: empty)
 */

if (PHP_SAPI !== 'cli') {
    fwrite(STDERR, "This command must be run from the command line.\n");
    exit(1);
}

$basePath = dirname(__DIR__);
$envPath = $basePath . '/.env';

if (is_file($envPath)) {
    fwrite(STDERR, "Refusing to overwrite existing .env. Delete or rename it first if you intend to reinstall.\n");
    exit(1);
}

function randomSecret(int $bytes = 32): string
{
    return rtrim(strtr(base64_encode(random_bytes($bytes)), '+/', '-_'), '=');
}

function promptValue(string $label, string $default = ''): string
{
    fwrite(STDOUT, $label . ($default !== '' ? ' [' . $default . ']' : '') . ': ');
    $line = fgets(STDIN);
    if ($line === false) {
        return $default;
    }
    $value = trim($line);
    return $value !== '' ? $value : $default;
}

function promptSecret(string $label): string
{
    if (!stream_isatty(STDIN)) {
        return promptValue($label);
    }

    if (DIRECTORY_SEPARATOR === '\\') {
        $script = '$s = Read-Host -AsSecureString; $b = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($s); [Runtime.InteropServices.Marshal]::PtrToStringBSTR($b)';
        $output = shell_exec('powershell -NoProfile -NonInteractive -Command ' . escapeshellarg($script));
        return trim((string) $output);
    }

    fwrite(STDOUT, $label . ': ');
    shell_exec('stty -echo');
    $value = trim((string) fgets(STDIN));
    shell_exec('stty echo');
    fwrite(STDOUT, "\n");
    return $value;
}

$adminUser = getenv('MYSQL_ADMIN_USER') ?: 'root';
$adminPassword = getenv('MYSQL_ADMIN_PASSWORD');
if ($adminPassword === false) {
    $adminPassword = stream_isatty(STDIN)
        ? promptSecret('MySQL administrator password (leave blank for Laragon root)')
        : '';
}

$host = '127.0.0.1';
$port = 3306;
$database = 'axa_kenneth_db';
$appUser = 'axa_kenneth_app';
$migrationUser = 'axa_kenneth_migrator';

foreach (['database' => $database, 'application user' => $appUser, 'migration user' => $migrationUser] as $label => $identifier) {
    if (!preg_match('/^[A-Za-z0-9_]+$/', $identifier)) {
        fwrite(STDERR, "Invalid {$label} identifier.\n");
        exit(1);
    }
}

$appPassword = randomSecret(32);
$migrationPassword = randomSecret(32);
$appKey = bin2hex(random_bytes(32));

try {
    $adminPdo = new PDO(
        sprintf('mysql:host=%s;port=%d;charset=utf8mb4', $host, $port),
        $adminUser,
        $adminPassword,
        [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_EMULATE_PREPARES => true,
            PDO::ATTR_TIMEOUT => 5,
        ]
    );

    $existingTables = $adminPdo->prepare(
        'SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = :schema'
    );
    $existingTables->execute([':schema' => $database]);
    $tableCount = (int) $existingTables->fetchColumn();

    if ($tableCount > 0) {
        fwrite(STDERR, "Database {$database} already contains tables. No changes were made. Use the migration runner instead.\n");
        exit(1);
    }

    $adminPdo->exec(
        "CREATE DATABASE IF NOT EXISTS `{$database}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"
    );

    $appPasswordSql = $adminPdo->quote($appPassword);
    $migrationPasswordSql = $adminPdo->quote($migrationPassword);

    foreach (['localhost', '127.0.0.1'] as $accountHost) {
        $adminPdo->exec("CREATE USER IF NOT EXISTS '{$appUser}'@'{$accountHost}' IDENTIFIED BY {$appPasswordSql}");
        $adminPdo->exec("ALTER USER '{$appUser}'@'{$accountHost}' IDENTIFIED BY {$appPasswordSql}");
        $adminPdo->exec("GRANT SELECT, INSERT, UPDATE, DELETE ON `{$database}`.* TO '{$appUser}'@'{$accountHost}'");

        $adminPdo->exec("CREATE USER IF NOT EXISTS '{$migrationUser}'@'{$accountHost}' IDENTIFIED BY {$migrationPasswordSql}");
        $adminPdo->exec("ALTER USER '{$migrationUser}'@'{$accountHost}' IDENTIFIED BY {$migrationPasswordSql}");
        $adminPdo->exec(
            "GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, DROP, REFERENCES ON `{$database}`.* TO '{$migrationUser}'@'{$accountHost}'"
        );
    }

    $env = <<<ENV
# Generated by scripts/setup-local-database.php on %s
APP_NAME="Kenneth | AXA Philippines"
APP_ENV=local
APP_DEBUG=false
APP_URL=http://axa-kenmark.test
APP_KEY=%s
APP_TIMEZONE=Asia/Manila

SESSION_NAME=axa_kenneth_session
SESSION_IDLE_MINUTES=30
SESSION_ABSOLUTE_HOURS=8
TRUST_PROXY_HEADERS=false
PRIVACY_NOTICE_VERSION=2026-10-22

DB_HOST=%s
DB_PORT=%d
DB_NAME=%s
DB_USER=%s
DB_PASSWORD=%s
DB_CHARSET=utf8mb4

DB_MIGRATION_USER=%s
DB_MIGRATION_PASSWORD=%s

MEDIA_MAX_BYTES=5242880
ENV;

    $env = sprintf(
        $env,
        date('c'),
        $appKey,
        $host,
        $port,
        $database,
        $appUser,
        $appPassword,
        $migrationUser,
        $migrationPassword
    );

    if (file_put_contents($envPath, $env, LOCK_EX) === false) {
        throw new RuntimeException('Unable to write .env.');
    }
    @chmod($envPath, 0600);

    // Verify both accounts can authenticate before reporting success.
    new PDO(
        sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $host, $port, $database),
        $appUser,
        $appPassword,
        [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_TIMEOUT => 5]
    );
    new PDO(
        sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $host, $port, $database),
        $migrationUser,
        $migrationPassword,
        [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_TIMEOUT => 5]
    );

    fwrite(STDOUT, "Database and least-privilege accounts created.\n");
    fwrite(STDOUT, ".env written with newly generated credentials (not displayed).\n");
    fwrite(STDOUT, "Next: php scripts/migrate.php && php scripts/seed.php && php scripts/create-admin.php\n");
} catch (Throwable $exception) {
    fwrite(STDERR, 'Setup failed: ' . $exception->getMessage() . "\n");
    exit(1);
}
